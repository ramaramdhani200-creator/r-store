-- R-STOREPEDIA SMM schema for Supabase PostgreSQL
-- Run in Supabase Dashboard > SQL Editor. Review this schema before production.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'user' check (role in ('user','admin')),
  balance bigint not null default 0 check (balance >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  platform text not null check (platform in ('Instagram','TikTok','YouTube','Facebook')),
  service text not null,
  target_url text not null,
  quantity integer not null check (quantity between 10 and 100000),
  charge_amount bigint not null check (charge_amount >= 0),
  status text not null default 'pending' check (status in ('pending','processing','completed','partial','failed','cancelled')),
  provider_order_id text,
  created_at timestamptz not null default now()
);

create table if not exists public.deposit_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount bigint not null check (amount >= 10000),
  method text not null,
  status text not null default 'pending' check (status in ('pending','paid','failed','expired','cancelled')),
  gateway_reference text unique,
  payment_url text,
  created_at timestamptz not null default now()
);

-- Automatically create a user profile at sign-up.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email) values (new.id, new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.orders enable row level security;
alter table public.deposit_requests enable row level security;

-- SECURITY DEFINER helper avoids recursive RLS checks when testing the admin role.
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin');
$$;

-- Users can read their own profile. No client-side balance/role updates permitted.
drop policy if exists "profile read own or admin" on public.profiles;
create policy "profile read own or admin" on public.profiles for select to authenticated
using (id = auth.uid() or public.is_admin());

-- Users can create/read only their own orders. Updates are intentionally disabled for customers.
drop policy if exists "orders read own or admin" on public.orders;
create policy "orders read own or admin" on public.orders for select to authenticated
using (user_id = auth.uid() or public.is_admin());
drop policy if exists "orders insert own" on public.orders;
create policy "orders insert own" on public.orders for insert to authenticated
with check (user_id = auth.uid() and status = 'pending');

-- Users can create/read only their own deposit requests; no client-side marking as paid.
drop policy if exists "deposits read own or admin" on public.deposit_requests;
create policy "deposits read own or admin" on public.deposit_requests for select to authenticated
using (user_id = auth.uid() or public.is_admin());
drop policy if exists "deposits insert own" on public.deposit_requests;
create policy "deposits insert own" on public.deposit_requests for insert to authenticated
with check (user_id = auth.uid() and status = 'pending');

